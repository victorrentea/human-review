// Progressive disclosure over the inlined sequence-diagram SVGs. The generator wrapped
// the label of every arrow that has more to say in a PlantUML link, which PlantUML
// rendered as <a href="genseq://<id>"> — a stable, generation-time handle, so nothing
// here has to match rendered label text. The detail itself rides in the sidecar next to
// each diagram. Resting on a label previews its detail, one click keeps it open, another
// closes.
//
// Where a step has a second rendering of the same fact — a statement as sent vs. the
// same statement with its bound values put back — the panel offers it as a toggle. It
// used to be a second click on the arrow, which swapped the text under the reader and
// counted itself "1 / 2": both the affordance and the fact that there *was* one were
// invisible until you had already found them by accident.
(function () {
  var PREFIX = 'genseq://';
  // The section header's handle. The generator writes a line number rather than a path — the
  // .puml is committed and read on other machines — and the file it belongs to is the one the
  // diagram is already labelled `generated by`.
  var SCENARIO_PREFIX = 'genseq-scenario://';
  // `?` or the bound values is a way of reading, not a property of one arrow: a reviewer
  // who asked for values once is reading the whole page in values. So the choice is the
  // page's, and every panel opened after it honours it.
  var showValues = false;
  // Two panels, because a preview must not disturb what is kept: `held`, the one a click
  // opened (`current` is the arrow it belongs to), and `peek`, the one a resting pointer
  // opened. Crossing other labels on the way to the held panel leaves it where it is.
  var held = null, current = null;
  var peek = null, peeking = null, peekTimer = null;
  // tip.js's own wait: long enough that a pointer crossing a diagram opens nothing.
  var PEEK_DELAY = 150;
  // The test a diagram was generated from, computed at build time. Inside a test pair the
  // heading above the picture already names that file, so the card prints no `generated by`
  // line of its own and the href rides on the card instead; a diagram standing alone still
  // carries the provenance paragraph, and that is the fallback.
  // The link's own address, whichever IDE its href now names (`HR.codeHref`, editor.js).
  function code(a) { return a.getAttribute('data-hr-code') || a.getAttribute('href'); }
  function sourceOf(diagram) {
    var direct = diagram.getAttribute('data-test-src');
    if (direct) return direct;
    var links = diagram.querySelectorAll('.prov .srcref');
    // The test first, explicitly: the second provenance link is the .puml, and a scenario's
    // line number resolved against a generated file would point at nothing.
    for (var i = 0; i < links.length; i++) {
      if (/^generated by /.test(links[i].textContent || '')) return code(links[i]);
    }
    return links.length ? code(links[0]) : null;
  }

  // The provenance link opens the file at its first line; a section header knows better.
  function atLine(href, line) {
    return href ? href.replace(/(:\d+){0,2}$/, '') + ':' + line + ':1' : null;
  }

  // Give an element's children back to its parent and drop it — used where a handle turns out
  // to lead nowhere, since removing the <a> would take the text it wraps with it.
  function unwrap(node) {
    while (node.firstChild) node.parentNode.insertBefore(node.firstChild, node);
    node.remove();
  }

  // Through the page's one way to source (`HR.openCode`, editor.js), never `location.href`:
  // the reader may have picked IntelliJ, or no IDE at all.
  function openSource(href) {
    if (href) window.HR.openCode(href);
  }

  function buildPanel(id) {
    var panel = document.createElement('div');
    panel.id = id;
    panel.className = 'genseq-panel';
    panel.hidden = true;
    panel.innerHTML =
      // The handler rides in the head, right after `Backend → NotificationService:` — the
      // place the route used to be repeated from the arrow the reader had just clicked.
      '<div class="genseq-head"><span class="genseq-title"></span>' +
      '<a class="genseq-handler srcref" data-tip="Open in VS Code" hidden></a>' +
      // `genseq-value`: the badge wears the marks' colours, since it names what they show.
      '<button type="button" class="genseq-toggle genseq-value" hidden></button>' +
      '<span class="genseq-grow"></span><span class="genseq-step"></span>' +
      '<span class="genseq-keep">click to keep it open</span>' +
      '<button type="button" class="genseq-close" data-tip="close (Esc)" aria-label="close">&times;</button></div>' +
      // `code`: the page's Pygments token colours are scoped to `pre.code` (tokenize, below).
      '<div class="genseq-label"></div><pre class="code"></pre>';
    document.body.appendChild(panel);
    return {
      root: panel,
      step: null,
      title: panel.querySelector('.genseq-title'),
      counter: panel.querySelector('.genseq-step'),
      handler: panel.querySelector('.genseq-handler'),
      label: panel.querySelector('.genseq-label'),
      toggle: panel.querySelector('.genseq-toggle'),
      body: panel.querySelector('pre'),
    };
  }

  function heldPanel() {
    if (held) return held;
    held = buildPanel('genseq-panel');
    var panel = held.root;
    panel.querySelector('.genseq-close').addEventListener('click', close);
    // The title is a label, not a control. ⌘-click on it used to open the diagram's test
    // — a door with no handle, opening what the section header above the picture opens on
    // a plain click, and at the right line rather than at line 1.
    held.toggle.addEventListener('click', function () { showValues = !showValues; render(held); });
    // A click inside the panel is not a click outside it, so it does not close it — said in
    // the closing listener (`outside`, below) rather than by stopping the click here: the
    // handler link's click has to reach editor.js's listener on `document`, which opens it
    // in the picked IDE. Stopped here, it fell through to its bare `vscode://` href and
    // opened VS Code with IntelliJ picked (Victor, 29 Oct 2026).
    enableDrag(panel, panel.querySelector('.genseq-head'));
    return held;
  }

  // The preview takes no pointer and no focus: it can open over the label that opened it, and
  // a panel that caught the pointer would close itself by doing so, then reopen, in a loop.
  function peekPanel() {
    if (peek) return peek;
    peek = buildPanel('genseq-peek');
    peek.root.inert = true;
    return peek;
  }

  // The head is the handle: drag it to push the panel aside and see the diagram under it.
  // Same page coordinates as place() (left/top on an absolutely positioned element), so a
  // scroll mid-drag cannot desync them. Buttons in the head keep their clicks.
  function enableDrag(panel, head) {
    var drag = null;
    head.addEventListener('pointerdown', function (ev) {
      if (ev.button !== 0 || ev.target.closest('button, a')) return;
      drag = { x: ev.clientX, y: ev.clientY,
               left: parseFloat(panel.style.left) || panel.offsetLeft,
               top: parseFloat(panel.style.top) || panel.offsetTop };
      head.setPointerCapture(ev.pointerId);
      ev.preventDefault();
    });
    head.addEventListener('pointermove', function (ev) {
      if (!drag) return;
      panel.style.left = (drag.left + ev.clientX - drag.x) + 'px';
      panel.style.top = (drag.top + ev.clientY - drag.y) + 'px';
    });
    function end() { drag = null; }
    head.addEventListener('pointerup', end);
    head.addEventListener('pointercancel', end);
  }

  function unpeek() {
    clearTimeout(peekTimer);
    peeking = null;
    if (peek) peek.root.hidden = true;
  }

  function close() {
    unpeek();
    if (current) current.reset();
    current = null;
    if (held) held.root.hidden = true;
  }

  // A pointer resting on a label, or the keyboard landing on it. The arrow already open is
  // left alone: its detail is on screen.
  function peekAt(state) {
    if (state === peeking) return;
    unpeek();
    if (state === current) return;
    peeking = state;
    peekTimer = setTimeout(function () {
      show(peekPanel(), state.entry, 0, state.link, true);
    }, PEEK_DELAY);
  }

  // Page coordinates, and anchored to the arrow rather than to the pointer: the panel
  // must stay put while the page scrolls, and still be readable next to what it explains.
  function place(into, target, volatile) {
    var box = target.getBoundingClientRect(), panel = into.root;
    panel.hidden = false;
    // Measured from the page's corner: at its last place by the window's edge the panel
    // shrinks to what is left of the window, and that is not the size it is about to have.
    panel.style.left = panel.style.top = '0';
    var width = panel.offsetWidth, height = panel.offsetHeight;
    var viewWidth = document.documentElement.clientWidth, view = document.documentElement.clientHeight;
    var top;
    if (box.right + 16 + width <= viewWidth - 12) {
      // To the right of the label, level with its row: dropped under the label, it covered
      // the arrows below it — the ones a reader clicks through next (Victor, 27 Oct 2026).
      // Lifted when the window's foot would cut it, never above the window's top.
      panel.style.left = (box.right + 16 + window.scrollX) + 'px';
      top = Math.max(8, Math.min(box.top - 6, view - height - 8));
    } else {
      var left = Math.min(box.left + window.scrollX, window.scrollX + viewWidth - width - 12);
      panel.style.left = Math.max(window.scrollX + 8, left) + 'px';
      // No room beside it: below the arrow when it fits, else above it; when neither does,
      // below, and the page scrolls just enough to show it whole. Opened near the window's
      // foot, it used to hang off the bottom, its scrollbar and the end of a long statement
      // with it.
      top = box.bottom + 8;
      if (top + height > view && box.top - 8 - height >= 0) top = box.top - 8 - height;
    }
    // A preview never scrolls the page under the pointer, so it stays inside the window
    // instead. It lets the pointer through (`peekPanel`), so covering the label is harmless.
    if (volatile) top = Math.max(8, Math.min(top, view - height - 8));
    panel.style.top = (top + window.scrollY) + 'px';
    if (volatile) return;
    var over = top + height + 8 - view;
    if (over > 0) window.scrollBy(0, Math.min(over, Math.max(0, box.top - 60)));
  }

  // Where each bound value sits in the statement with its values put back, found by laying
  // it over the statement as sent: the text between two `?` is the same in both, so a value
  // runs from where one piece of it ends to where the next one starts. A quoted value is
  // read to its closing quote first, since it may itself contain that next piece. Null when
  // the two do not line up — the text is then shown plain, as it always was.
  function valueSpans(sent, bound) {
    var pieces = sent.split('?');
    if (pieces.length < 2 || bound.indexOf(pieces[0]) !== 0) return null;
    var spans = [], pos = pieces[0].length;
    for (var i = 1; i < pieces.length; i++) {
      var next = pieces[i], from = pos, end;
      if (bound.charAt(pos) === "'") {
        from = pos + 1;
        while (from < bound.length && !(bound.charAt(from) === "'" && bound.charAt(from + 1) !== "'")) {
          from += bound.charAt(from) === "'" ? 2 : 1;
        }
        from++;
      }
      if (i === pieces.length - 1) {
        end = bound.length - next.length;
        if (end < from || bound.slice(end) !== next) return null;
      } else {
        end = next ? bound.indexOf(next, from) : from;
        if (end < 0) return null;
      }
      spans.push([pos, end]);
      pos = end + next.length;
    }
    return spans;
  }

  // Where each `?` sits in the statement as sent — the same holes the values fill.
  function placeholderSpans(sent) {
    var spans = [], at = -1;
    while ((at = sent.indexOf('?', at + 1)) >= 0) spans.push([at, at + 1]);
    return spans;
  }

  // Syntax colours for the body (Victor, 20 Oct 2026: "add syntax coloring to this SQL
  // snippet, as well as to the JSON"). Not a second palette: the tokens carry Pygments' own
  // short class names, and the <pre> is a `pre.code`, so the light and dark token colours
  // `extract-snippet.py --css` already puts on the page for every code snippet apply here
  // too. A body is one of two things — a JSON payload, or a SQL statement — and the first
  // character tells them apart; anything a pattern does not claim stays plain text.
  var SQL_WORDS = new RegExp('^(?:' + ('select|from|where|and|or|not|in|is|null|like|ilike|escape|' +
    'between|exists|join|left|right|inner|outer|full|cross|on|using|as|distinct|all|any|' +
    'insert|into|values|update|set|delete|returning|order|group|by|having|limit|offset|' +
    'fetch|first|next|rows|row|only|asc|desc|nulls|last|union|intersect|except|case|when|' +
    'then|else|end|with|recursive|for|true|false|cast|count|sum|min|max|avg|coalesce|' +
    'lower|upper|default|create|table|alter|drop|index|primary|key|references|constraint|' +
    'unique|lock|nowait|skip|locked|share|current_date|current_timestamp') + ')$', 'i');
  var SQL_TOKENS = /(--[^\n]*)|(\/\*[\s\S]*?(?:\*\/|$))|('(?:[^']|'')*'?)|("(?:[^"]|"")*"?)|(\b\d+(?:\.\d+)?(?:[eE][+-]?\d+)?\b)|([A-Za-z_][\w$]*)|([=<>!|+\-*\/%]+)/g;
  var JSON_TOKENS = /("(?:[^"\\\n]|\\.)*"?)(\s*:)?|(-?\d+(?:\.\d+)?(?:[eE][+-]?\d+)?)|\b(true|false|null)\b/g;

  // [start, end, class] for every coloured run of `text`, in order.
  function tokenize(text) {
    var out = [], m, json = /^\s*[\[{]/.test(text);
    var rx = json ? JSON_TOKENS : SQL_TOKENS;
    rx.lastIndex = 0;
    while ((m = rx.exec(text))) {
      if (!m[0]) { rx.lastIndex++; continue; }
      var at = m.index, cls = null, len = m[0].length;
      if (json) {
        // A key is a string followed by `:` — only the string is coloured, not the colon.
        if (m[1]) { cls = m[2] ? 'nt' : 's2'; len = m[1].length; }
        else if (m[3]) cls = /[.eE]/.test(m[3]) ? 'mf' : 'mi';
        else if (m[4]) cls = 'kc';
      } else if (m[1]) cls = 'c1';
      else if (m[2]) cls = 'cm';
      else if (m[3]) cls = 's1';
      else if (m[4]) cls = 'n';                       // a quoted identifier: a name
      else if (m[5]) cls = /[.eE]/.test(m[5]) ? 'mf' : 'mi';
      else if (m[6]) cls = /^(?:null|true|false)$/i.test(m[6]) ? 'kc' : SQL_WORDS.test(m[6]) ? 'k' : null;
      else if (m[7]) cls = 'o';
      if (cls) out.push([at, at + len, cls]);
    }
    return out;
  }

  // `text[from, to)` into `parent`, coloured by the tokens that overlap it — a token cut by a
  // mark's edge is coloured on both sides of it.
  function appendColoured(parent, text, tokens, from, to) {
    var at = from;
    tokens.forEach(function (t) {
      var s = Math.max(t[0], from), e = Math.min(t[1], to);
      if (e <= s) return;
      if (s > at) parent.appendChild(document.createTextNode(text.slice(at, s)));
      var span = document.createElement('span');
      span.className = t[2];
      span.textContent = text.slice(s, e);
      parent.appendChild(span);
      at = e;
    });
    if (to > at) parent.appendChild(document.createTextNode(text.slice(at, to)));
  }

  // Both renderings mark the same holes: the `?` as sent, and what was put back into each —
  // otherwise `=1` reads as a literal the query always had, and toggling makes the eye hunt
  // for what changed. Only a statement that lines up with its values is marked, which is
  // also what tells a placeholder from a `?` that is just text. Inside a mark the text is
  // plain: the mark's own solid colours are what say "this is the hole", in either view.
  function renderBody(view, text, on) {
    var step = view.step, bound = step.alternate && valueSpans(step.text, step.alternate.text);
    var spans = !bound ? [] : on ? bound : placeholderSpans(text);
    var tokens = tokenize(text);
    view.body.textContent = '';
    var at = 0;
    spans.forEach(function (span) {
      appendColoured(view.body, text, tokens, at, span[0]);
      var mark = document.createElement('mark');
      mark.className = 'genseq-value';
      mark.textContent = text.slice(span[0], span[1]);
      view.body.appendChild(mark);
      at = span[1];
    });
    appendColoured(view.body, text, tokens, at, text.length);
  }

  // The button always names the *other* rendering, so it reads as what a click will get
  // you. A step with no alternate — a JSON payload — simply has no button.
  function render(view) {
    var step = view.step, on = showValues && !!step.alternate;
    var shown = on ? step.alternate : step;
    view.label.textContent = shown.label || '';
    view.label.hidden = !shown.label;
    renderBody(view, shown.text, on);
    view.toggle.hidden = !step.alternate;
    if (step.alternate) {
      // One word, because it sits against the end of the title and the sentence it
      // completes is the title: `OwnerRepository.findById` … `values`. "show values"
      // spent half its width restating that a button is a thing you press.
      view.toggle.textContent = on ? '?' : 'values';
      view.toggle.setAttribute('aria-label', on ? 'show ?' : 'show values');
      view.toggle.setAttribute('data-tip', on
        ? 'the statement as sent, with ? for each bound value'
        : 'the same statement with the bound values put back');
      view.toggle.setAttribute('aria-pressed', on ? 'true' : 'false');
    }
  }

  // The entry point that answered the call. The arrow already carries the route, which is
  // the contract — so the head no longer repeats it (the build cut it from the title) and
  // names, in its place, the method that receives the request, in the service the arrow
  // points at. No trace knows that name: the build resolved the route against this
  // checkout's controllers, so the link lands on the real declaration line.
  function renderHandler(view, entry) {
    var handler = entry.handler;
    view.handler.hidden = !handler;
    view.title.textContent = entry.title + (handler ? ':' : '');
    if (!handler) { view.handler.removeAttribute('href'); return; }
    view.handler.textContent = handler.name + '()';
    view.handler.href = handler.href;
  }

  function show(view, entry, index, target, volatile) {
    view.step = entry.steps[index];
    view.counter.textContent = entry.steps.length > 1 ? (index + 1) + ' / ' + entry.steps.length : '';
    renderHandler(view, entry);
    render(view);
    place(view, target, volatile);
  }

  // A transparent rect under the arrow, so the click lands anywhere across the band
  // instead of only on the glyph PlantUML made into a link.
  function addHitArea(group) {
    var box;
    try { box = group.getBBox(); } catch (e) { return; }
    if (!box || !box.width) return;
    var rect = document.createElementNS('http://www.w3.org/2000/svg', 'rect');
    rect.setAttribute('class', 'genseq-hit');
    rect.setAttribute('x', box.x - 4);
    rect.setAttribute('y', box.y - 1);
    rect.setAttribute('width', box.width + 8);
    rect.setAttribute('height', Math.max(box.height - 2, 6));
    rect.setAttribute('rx', '3');
    group.insertBefore(rect, group.firstChild);
  }

  // One arrow, one click handler, though a label wrapped in two lines is two links with one
  // address: a handler per link meant the second click closed the panel and reopened it.
  function wireArrow(group, entry, link) {
    var state = group.__hrGenseqState;
    if (state) { state.link = link; return state; }
    var index = -1;
    state = group.__hrGenseqState = {entry: entry, link: link,
      reset: function () { index = -1; group.classList.remove('genseq-open'); }};
    group.classList.add('genseq-hot');
    addHitArea(group);
    group.addEventListener('click', function (ev) {
      // A browser request's words open the line that sent it and its ⊕ the body, in one
      // arrow: that other link keeps its click, for editor.js to take on `document`.
      var hit = ev.target.closest && ev.target.closest('a');
      if (hit && (hit.getAttribute('href') || '').indexOf(PREFIX) !== 0) return;
      ev.preventDefault();
      ev.stopPropagation();
      unpeek();
      // One arrow, one gesture. ⌘-click used to open the test from here as well, which
      // was a second way to reach what the section header above already opens — and a
      // chord the page had to spend a sentence explaining.
      if (current && current !== state) current.reset();
      index++;
      if (index >= entry.steps.length) { close(); return; }
      current = state;
      group.classList.add('genseq-open');
      show(heldPanel(), entry, index, state.link);
    });
    return state;
  }

  // Per diagram, over the page at load and over whatever a rebuild swaps in (`hr:swapped`,
  // at the bottom): a swapped-in panel's arrows arrive with no handles on them.
  function wireDiagrams(root) {
  var all = [].slice.call(root.querySelectorAll('.diagram'));
  if (root.matches && root.matches('.diagram')) all.unshift(root);
  all.forEach(function (diagram) {
    if (diagram.__hrGenseq) return;
    diagram.__hrGenseq = true;
    // Every carrier, not the first: a diagram is drawn twice in one card
    // (New / Old), and each side's handles are keyed by ids derived from that
    // side's payloads. One carrier covered one side, and the other panes' handles were
    // dropped as dead. Merged work-tree-first; the ids are content-derived, so an id
    // present on both sides carries the same payload either way.
    var carriers = diagram.querySelectorAll('script.genseq-details');
    if (!carriers.length) return;
    var details = {};
    for (var c = carriers.length - 1; c >= 0; c--) {
      var part = (JSON.parse(carriers[c].textContent) || {}).details || {};
      for (var key in part) details[key] = part[key];
    }
    var href = sourceOf(diagram);

    diagram.querySelectorAll('svg a[href^="' + SCENARIO_PREFIX + '"]').forEach(function (link) {
      var target = atLine(href, (link.getAttribute('href') || '').slice(SCENARIO_PREFIX.length));
      // Nothing to open — a diagram whose test is not in this checkout. Leave the title as
      // the plain text it would have been rather than an underline that leads nowhere.
      if (!target) { unwrap(link); return; }
      link.addEventListener('click', function (ev) {
        ev.preventDefault();
        ev.stopPropagation();
        openSource(target);
      });
    });

    diagram.querySelectorAll('svg a[href^="' + PREFIX + '"]').forEach(function (link) {
      var entry = details[(link.getAttribute('href') || '').slice(PREFIX.length)];
      var group = link.closest('g.message') || link.parentNode;
      // An arrow this change *removed* is re-inserted from the base diagram, and its
      // detail was never recorded here. Drop the handle rather than offer a dead one —
      // by unwrapping it, since the link is now around the label itself and removing
      // the element would take the arrow's text with it.
      if (!entry || !entry.steps.length) {
        unwrap(link);
        return;
      }

      var state = wireArrow(group, entry, link);
      // The preview says what the "Click for…" tip used to promise, so that tip goes: two
      // bubbles would open over one label. `xlink:title` is the browser's native copy of it.
      link.removeAttribute('data-tip');
      link.removeAttributeNS('http://www.w3.org/1999/xlink', 'title');
      // The two lines of a wrapped label are one label: crossing from one to the other is
      // not leaving it.
      function leave(ev) {
        var to = ev.relatedTarget && ev.relatedTarget.closest && ev.relatedTarget.closest('a');
        var same = to && group.contains(to) && to.getAttribute('href') === link.getAttribute('href');
        if (peeking === state && !same) unpeek();
      }
      // On the label, not on the arrow's whole band: a pointer resting on a line is not
      // asking for anything, and an edge's band on the Structure tab is its whole bounding box.
      // Mouse only: a finger has no resting, its tap goes straight to the click.
      link.addEventListener('pointerenter', function (ev) {
        if (ev.pointerType !== 'touch') peekAt(state);
      });
      link.addEventListener('pointerleave', leave);
      // The keyboard's way to the same preview, and not the focus a mouse click leaves behind.
      link.addEventListener('focus', function () {
        if (link.matches(':focus-visible')) peekAt(state);
      });
      link.addEventListener('blur', leave);
    });

    // No instructions above the picture. There used to be a line here — "Click any arrow
    // marked ⊕ for the SQL or the JSON behind it" — printed once per diagram, and on a
    // tab that is now one picture per test that is once per test. The ⊕ is on the label
    // itself, the cursor changes over it, and resting there shows what a click would keep,
    // at the moment the reader is looking at it. A sentence above the diagram says the
    // same thing to everyone, including the reader who has already clicked one.
  });
  }
  wireDiagrams(document);

  // The generator ends a label that opens a method in the editor with `↗`. The label is
  // already a link, so the glyph goes and nothing replaces it (Victor, 20 Oct 2026: "no
  // IntelliJ icon there, just a hyperlink is enough").
  var IDE_GLYPH = /\s*↗\s*$/;

  // The last text node of `text`, so a label split into tspans keeps its other runs.
  function stripGlyph(text) {
    var node = text;
    while (node && node.nodeType !== 3) node = node.lastChild;
    if (!node) return false;
    if (!IDE_GLYPH.test(node.nodeValue)) return false;
    node.nodeValue = node.nodeValue.replace(IDE_GLYPH, '');
    if (!text.textContent.trim()) text.remove();
    return true;
  }

  function wireGlyphs(root) {
    root.querySelectorAll('.diagram svg a').forEach(function (link) {
      var texts = link.querySelectorAll('text');
      for (var i = texts.length - 1; i >= 0 && !stripGlyph(texts[i]); i--) {}
    });
  }
  wireGlyphs(document);

  // The panel is placed in page coordinates, so a diagram scrolled sideways under it
  // would leave it pointing at the wrong arrow.
  function wireScroll(root) {
    root.querySelectorAll('.diagram .svgbox').forEach(function (box) {
      box.addEventListener('scroll', close);
    });
  }
  wireScroll(document);
  document.addEventListener('click', function outside(ev) {
    if (held && held.root.contains(ev.target)) return;
    close();
  });
  // A rebuild swapped part of the page (`panels.js`, `rerun.js`): the open detail may point
  // at an arrow that is gone, and the new arrows need their handles.
  document.addEventListener('hr:swapped', function (ev) {
    var root = ev.detail;
    if (!root || !root.querySelectorAll) return;
    close();
    wireDiagrams(root);
    wireGlyphs(root);
    wireScroll(root);
  });
  document.addEventListener('keydown', function (ev) { if (ev.key === 'Escape') close(); });
})();
