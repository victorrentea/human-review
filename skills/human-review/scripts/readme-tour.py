#!/usr/bin/env python3
"""Shoot the featured demo snapshot tab by tab, and put the pictures where readers land.

The README described thirteen tabs in prose, and a reader had to open the demo to find out
what any of them looked like (issue #1: *less text, more screenshots*). This is the fix,
made so that it cannot go stale: every time the featured snapshot is published,
`publish-demo.sh` calls this, and it

  1. serves `demo/` over HTTP exactly as GitHub Pages will, opens `<slug>/review.html` in
     headless Chromium, clicks through every tab and takes one viewport-sized JPEG of each
     — `demo/<slug>/tour/<panel>.jpg`, beside the snapshot it shows, so a republish that
     wipes the snapshot wipes its pictures with it;
  2. rewrites the README's two managed regions — the hero shot under the intro (the links to
     the demos are the hand-written bullets at the top), and the tour (one full-width picture, one caption and one page per tab);
  3. rewrites the screenshot at the top of each tab's page under `docs/tabs/`;
  4. rewrites the featured block at the top of `demo/index.html`, the Pages landing page,
     so the site's root leads straight into the demo.

Everything outside the markers is hand-written and never touched. The one-line summary of
each tab lives in its own page (`docs/tabs/*.md`, the `>` line under the heading), so the
README table is assembled from the pages instead of repeating them.

Which snapshot is featured is written in exactly one place, the README's own marker —
`<!-- featured-demo:begin slug=demo -->` — so every link this writes is derived from it
rather than typed. `--feature SLUG` moves it.

Playwright is imported lazily: CI runs `--help` on every script here with no browser.
"""

from __future__ import annotations

import argparse
import functools
import html
import http.server
import importlib.util
import json
import os
import re
import shutil
import subprocess
import sys
import threading
from pathlib import Path

HERE = Path(__file__).resolve().parent

VIEWPORT = {"width": 1440, "height": 900}
JPEG_QUALITY = 82

FEATURED_BEGIN = re.compile(r"<!-- featured-demo:begin(?: slug=([A-Za-z0-9_-]+))? -->")
FEATURED_END = "<!-- featured-demo:end -->"
TOUR_BEGIN = re.compile(r"<!-- tour:begin -->")
TOUR_END = "<!-- tour:end -->"
SHOT_BEGIN = re.compile(r"<!-- shot:begin -->")
SHOT_END = "<!-- shot:end -->"
LANDING_BEGIN = re.compile(r"<!-- featured:begin -->")
LANDING_END = "<!-- featured:end -->"

GENERATED = ("generated by `skills/human-review/scripts/readme-tour.py` on every publish "
             "of the featured snapshot — edits between these markers are overwritten")


# --------------------------------------------------------------------------------------
# text: pure functions, pinned by test_readme_tour.py


def featured_slug(readme: str) -> str | None:
    m = FEATURED_BEGIN.search(readme)
    return m.group(1) if m and m.group(1) else None


def replace_region(text: str, begin: re.Pattern, end: str, inner: str,
                   begin_marker: str | None = None) -> str:
    """Swap what sits between `begin` and `end` for `inner`; the markers themselves stay,
    unless `begin_marker` rewrites the opening one (it carries the featured slug)."""
    m = begin.search(text)
    if not m:
        raise ValueError(f"marker {begin.pattern!r} not found")
    stop = text.find(end, m.end())
    if stop < 0:
        raise ValueError(f"marker {end!r} not found after {begin.pattern!r}")
    opening = begin_marker if begin_marker is not None else m.group(0)
    return text[:m.start()] + opening + "\n" + inner.strip("\n") + "\n" + text[stop:]


def pages_base(repo: Path) -> str:
    """`https://<owner>.github.io/<repo>` from the origin remote, so a fork links to itself."""
    try:
        url = subprocess.run(["git", "-C", str(repo), "remote", "get-url", "origin"],
                             capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        url = ""
    m = re.search(r"github\.com[:/]([^/]+)/([^/]+?)(?:\.git)?/?$", url)
    if not m:
        return "https://victorrentea.github.io/human-review"
    return f"https://{m.group(1).lower()}.github.io/{m.group(2)}"


def read_tab_page(path: Path) -> dict | None:
    """The three facts the README needs from a tab's page: which panel it documents, its
    name, and its one-line summary. A page that names no panel is not a tab page."""
    text = path.read_text(encoding="utf-8")
    panel = re.search(r"<!-- panel: *([A-Za-z0-9_-]+) *-->", text)
    if not panel:
        return None
    title = re.search(r"^# +(.+?)\s*$", text, re.M)
    summary = re.search(r"^> +(.+?)\s*$", text, re.M)
    return {
        "panel": panel.group(1),
        "title": title.group(1) if title else panel.group(1),
        "summary": summary.group(1) if summary else "",
        "file": path.name,
    }


def render_featured(slug: str, base: str, title: str, hero: str | None) -> str:
    """The hero shot under the README's hand-written intro. The links to every demo sit in
    the bullets at the very top of the README; this only shows what one of them looks like."""
    live = f"{base}/{slug}/review.html"
    lines = [f"<!-- {GENERATED} -->"]
    if hero:
        lines += [f'<a href="{live}"><img src="{hero}" alt="{html.escape(title)} — '
                  f'the Review tab of the demo page" width="100%"></a>', ""]
    lines.append(f"<sub>**{html.escape(title)}**, Review tab — click to open it live. "
                 f"Every published snapshot: <{base}/></sub>")
    return "\n".join(lines)


def render_tour(slug: str, base: str, shots: list[dict], pages: dict[str, dict]) -> str:
    live = f"{base}/{slug}/review.html"
    blocks = []
    for shot in shots:
        page = pages.get(shot["panel"])
        img = f"demo/{slug}/tour/{shot['file']}"
        name = page["title"] if page else shot["title"]
        target = f"docs/tabs/{page['file']}" if page else img
        heading = f"### [{name}]({target})" if page else f"### {name}"
        caption = f"[open it live]({live}#{shot['panel']})"
        if page and page["summary"]:
            caption += f" — {page['summary']}"
        blocks += [
            heading,
            "",
            f'<a href="{target}"><img src="{img}" alt="{html.escape(name)} tab" width="100%"></a>',
            "",
            f"<sub>{caption}</sub>",
            "",
        ]
    return "\n".join([
        f"<!-- {GENERATED} -->",
        "One screenshot per tab of the demo, retaken on every publish.",
        "**Click a picture** for that tab's own page: what it shows, what it needs, how it works.",
        "",
        *blocks[:-1],
    ])


def render_tab_shot(slug: str, base: str, shot: dict | None, title: str) -> str:
    if not shot:
        return (f"<!-- {GENERATED} -->\n"
                f"*The featured demo (`{slug}`) has no {title} tab, so there is no screenshot "
                f"of it yet.*")
    live = f"{base}/{slug}/review.html#{shot['panel']}"
    return "\n".join([
        f"<!-- {GENERATED} -->",
        f'<a href="{live}"><img src="../../demo/{slug}/tour/{shot["file"]}" '
        f'alt="The {html.escape(title)} tab of the demo page" width="100%"></a>',
        "",
        f"[Open this tab in the live demo]({live}) · [all tabs](../../README.md#a-tour-one-tab-at-a-time)",
    ])


LANDING_CSS = """
  .featured { margin: 0 0 2.5rem; }
  .featured .hero { display: block; border: 1px solid var(--line); border-radius: 12px;
    overflow: hidden; background: var(--panel); transition: border-color .15s ease, transform .15s ease; }
  .featured .hero:hover { border-color: var(--accent); transform: translateY(-1px); }
  .featured .hero img { display: block; width: 100%; height: auto; }
  .featured .cta { display: flex; flex-wrap: wrap; align-items: center; gap: .6rem 1rem; margin: 1rem 0 1.2rem; }
  .featured .go { display: inline-block; background: var(--accent); color: var(--bg); font-weight: 600;
    text-decoration: none; padding: .6rem 1.15rem; border-radius: 999px; }
  .featured .go:hover { filter: brightness(1.1); }
  .featured .what { color: var(--muted); font-size: .92rem; }
  .featured .thumbs { list-style: none; margin: 0; padding: 0; display: grid;
    grid-template-columns: repeat(auto-fill, minmax(8.5rem, 1fr)); gap: .6rem; }
  .featured .thumbs a { display: block; text-decoration: none; color: var(--muted); font-size: .8rem; }
  .featured .thumbs img { display: block; width: 100%; aspect-ratio: 16 / 10; object-fit: cover;
    object-position: top; border: 1px solid var(--line); border-radius: 6px; margin-bottom: .2rem; }
  .featured .thumbs a:hover { color: var(--accent); }
  .featured .thumbs a:hover img { border-color: var(--accent); }
"""


def render_landing(slug: str, title: str, subtitle: str, shots: list[dict],
                   pages: dict[str, dict]) -> str:
    live = f"{slug}/review.html"
    hero = shots[0] if shots else None
    # The card is an <a>, and so is the hero: the subtitle keeps its text, loses its links.
    sub = re.sub(r"</?a\b[^>]*>", "", subtitle or "")
    out = [f"  <!-- {html.escape(GENERATED)} -->",
           f"  <style>{LANDING_CSS}  </style>",
           '  <section class="featured" aria-label="The live demo">']
    if hero:
        out.append(f'    <a class="hero" href="{live}"><img src="{slug}/tour/{hero["file"]}" '
                   f'alt="{html.escape(title)} — the review page, open on its first tab"></a>')
    out.append('    <p class="cta">'
               f'<a class="go" href="{live}">Open the live demo →</a>'
               f'<span class="what"><b>{html.escape(title)}</b>'
               + (f" — {sub}" if sub else "") + "</span></p>")
    if shots:
        out.append('    <ul class="thumbs">')
        for shot in shots:
            page = pages.get(shot["panel"])
            name = html.escape(page["title"] if page else shot["title"])
            out.append(f'      <li><a href="{live}#{shot["panel"]}">'
                       f'<img src="{slug}/tour/{shot["file"]}" alt="" loading="lazy">{name}</a></li>')
        out.append("    </ul>")
    out.append("  </section>")
    return "\n".join(out)


def ensure_landing_region(text: str) -> str:
    """First run: open the featured region under the page's lede, above everything else."""
    if LANDING_BEGIN.search(text):
        return text
    m = re.search(r'<p class="lede">.*?</p>\n', text, re.S)
    if not m:
        raise ValueError("demo/index.html has no <p class=\"lede\"> to put the demo under")
    return (text[:m.end()] + "\n  <!-- featured:begin -->\n  <!-- featured:end -->\n"
            + text[m.end():])


