def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="readme-tour.py",
        description=("Screenshot every tab of the featured demo snapshot and refresh the "
                     "README tour, the per-tab pages under docs/tabs/ and the featured block "
                     "on the Pages landing page. Called by publish-demo.sh."))
    parser.add_argument("--repo", default=os.environ.get("HUMAN_REVIEW_REPO",
                                                         str(Path.home() / "workspace/human-review")),
                        help="checkout of human-review (default: $HUMAN_REVIEW_REPO or ~/workspace/human-review)")
    parser.add_argument("--slug", default="",
                        help="only act if this is the featured snapshot (what publish-demo.sh passes)")
    parser.add_argument("--feature", default="",
                        help="make this snapshot the featured one, then refresh everything")
    parser.add_argument("--no-shoot", action="store_true",
                        help="keep the existing pictures, only rewrite the text around them")
    args = parser.parse_args(argv)

    repo = Path(args.repo).expanduser().resolve()
    readme_path = repo / "README.md"
    readme = readme_path.read_text(encoding="utf-8")
    featured = args.feature or featured_slug(readme)
    if not featured:
        raise SystemExit("readme-tour: README.md has no '<!-- featured-demo:begin slug=… -->' "
                         "marker; pass --feature SLUG once to set it")
    if args.slug and args.slug != featured:
        print(f"readme-tour: {args.slug} is not the featured snapshot ({featured}); "
              f"README left alone", file=sys.stderr)
        return 0

    snap = repo / "demo" / featured
    if not (snap / "review.html").is_file():
        raise SystemExit(f"readme-tour: no snapshot at {snap}")
    tour_dir = snap / "tour"
    manifest_path = tour_dir / "tour.json"

    content = {}
    try:
        content = json.loads((snap / "content.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        pass
    title = re.sub(r"<[^>]+>", "", content.get("title") or featured).strip()
    subtitle = content.get("subtitle") or ""

    if args.no_shoot:
        if not manifest_path.is_file():
            raise SystemExit(f"readme-tour: --no-shoot, but there are no pictures in {tour_dir}")
        shots = json.loads(manifest_path.read_text(encoding="utf-8"))["shots"]
    else:
        print(f"readme-tour: shooting demo/{featured}/review.html, tab by tab", file=sys.stderr)
        shots = shoot(repo / "demo", featured, tour_dir)
        manifest_path.write_text(json.dumps({"slug": featured, "title": title, "shots": shots},
                                            indent=2) + "\n", encoding="utf-8")

    base = pages_base(repo)
    pages: dict[str, dict] = {}
    page_paths: dict[str, Path] = {}
    for path in sorted((repo / "docs" / "tabs").glob("*.md")):
        info = read_tab_page(path)
        if info:
            pages[info["panel"]] = info
            page_paths[info["panel"]] = path

    by_panel = {s["panel"]: s for s in shots}
    hero = f"demo/{featured}/tour/{shots[0]['file']}" if shots else None

    readme = replace_region(readme, FEATURED_BEGIN, FEATURED_END,
                            render_featured(featured, base, title, hero),
                            begin_marker=f"<!-- featured-demo:begin slug={featured} -->")
    readme = replace_region(readme, TOUR_BEGIN, TOUR_END,
                            render_tour(featured, base, shots, pages))
    readme_path.write_text(readme, encoding="utf-8")

    for panel, path in page_paths.items():
        text = path.read_text(encoding="utf-8")
        if not SHOT_BEGIN.search(text):
            print(f"  ! {path.name}: no shot markers, left alone", file=sys.stderr)
            continue
        text = replace_region(text, SHOT_BEGIN, SHOT_END,
                              render_tab_shot(featured, base, by_panel.get(panel),
                                              pages[panel]["title"]))
        path.write_text(text, encoding="utf-8")
    for shot in shots:
        if shot["panel"] not in pages:
            print(f"  ! tab '{shot['title']}' ({shot['panel']}) has no page under docs/tabs/",
                  file=sys.stderr)

    landing_path = repo / "demo" / "index.html"
    landing = ensure_landing_region(landing_path.read_text(encoding="utf-8"))
    landing = replace_region(landing, LANDING_BEGIN, LANDING_END,
                             render_landing(featured, title, subtitle, shots, pages))
    landing_path.write_text(landing, encoding="utf-8")

    print(f"readme-tour: {len(shots)} tabs of '{featured}' -> README.md, docs/tabs/, "
          f"demo/index.html", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
