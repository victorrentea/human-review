def _shoot_module():
    """shoot-review.py already knows how to settle a panel, wake its lazy images and give a
    video a first frame; borrow that rather than keep a second copy that drifts."""
    spec = importlib.util.spec_from_file_location("shoot_review", HERE / "shoot-review.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


class _Quiet(http.server.SimpleHTTPRequestHandler):
    """Static files, plus the one thing `SimpleHTTPRequestHandler` lacks and Pages has:
    byte ranges. Without them Chromium cannot seek the feature video, and the Demo tab was
    shot on its title card with a spinner over it."""

    def log_message(self, *args):  # noqa: D401 — a request log per image is only noise
        pass

    def send_head(self):
        rng = re.fullmatch(r"bytes=(\d*)-(\d*)", self.headers.get("Range", "").strip())
        path = Path(self.translate_path(self.path))
        if not rng or not path.is_file():
            return super().send_head()
        size = path.stat().st_size
        first, last = rng.groups()
        if first:
            start, end = int(first), int(last) if last else size - 1
        else:
            start, end = max(0, size - int(last or 0)), size - 1
        end = min(end, size - 1)
        if start > end:
            self.send_error(416)
            return None
        f = path.open("rb")
        f.seek(start)
        self.send_response(206)
        self.send_header("Content-Type", self.guess_type(str(path)))
        self.send_header("Content-Range", f"bytes {start}-{end}/{size}")
        self.send_header("Content-Length", str(end - start + 1))
        self.send_header("Accept-Ranges", "bytes")
        self.end_headers()
        self._remaining = end - start + 1
        return f

    def copyfile(self, source, outputfile):
        remaining = getattr(self, "_remaining", None)
        if remaining is None:
            return super().copyfile(source, outputfile)
        self._remaining = None
        while remaining > 0:
            chunk = source.read(min(64 * 1024, remaining))
            if not chunk:
                break
            outputfile.write(chunk)
            remaining -= len(chunk)


def serve(root: Path):
    handler = functools.partial(_Quiet, directory=str(root))
    server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    return server


# JS click: a mouse click would leave the pointer on the tab strip, and the strip's hover
# tooltips would be in every picture.
CLICK_TAB_JS = "(i) => document.querySelectorAll('.tabstrip button.tab')[i].click()"

# After the seek, Chromium paints its buffering spinner over the frame until enough data
# is in to play on from it; wait for that (a ceiling, not a pace). The spinner then fades
# out inside the controls' shadow DOM, which FREEZE_CSS cannot reach and nothing reports,
# so a panel with a video is given SPINNER_FADE_MS more before it is shot.
SPINNER_FADE_MS = 2000
VIDEO_READY_JS = """
async (sel) => {
  const scope = sel ? document.querySelector(sel) : null;
  const videos = scope ? Array.from(scope.querySelectorAll('video')) : [];
  await Promise.all(videos.map((v) => v.readyState >= 3 ? null : new Promise((r) => {
    v.addEventListener('canplay', r, {once: true});
    setTimeout(r, 8000);
  })));
  return videos.length;
}
"""

# The Sequence tab opens with every test pair folded, which is right for a reader and makes
# a picture of five grey rows. Unfold the first pair, so the shot shows a diagram beside the
# test that drew it — which is what the tab is for.
UNFOLD_FIRST_JS = """
(sel) => {
  const scope = sel ? document.querySelector(sel) : null;
  if (!scope || scope.querySelector('details.testpair[open]')) return false;
  const first = scope.querySelector('details.testpair');
  if (first) first.open = true;
  return Boolean(first);
}
"""


def shoot(demo_root: Path, slug: str, out_dir: Path) -> list[dict]:
    sr = _shoot_module()
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        raise SystemExit(
            "readme-tour: playwright is not installed for this interpreter.\n"
            "             publish-demo.sh provisions it; or: pip install playwright && "
            "playwright install chromium")

    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)

    server = serve(demo_root)
    url = f"http://127.0.0.1:{server.server_address[1]}/{slug}/review.html"
    shots: list[dict] = []
    try:
        with sync_playwright() as pw:
            browser = pw.chromium.launch()
            context = browser.new_context(viewport=VIEWPORT, device_scale_factor=1,
                                          color_scheme="light", reduced_motion="reduce")
            page = context.new_page()
            page.goto(url, wait_until="load")
            page.add_style_tag(content=sr.FREEZE_CSS)
            try:
                page.wait_for_load_state("networkidle", timeout=15000)
            except Exception:  # noqa: BLE001 — a page that never idles is still shootable
                pass
            tabs = page.evaluate(sr.TAB_META_JS)
            if not tabs:
                raise SystemExit(f"readme-tour: {url} has no tab strip")
            for i, tab in enumerate(tabs):
                panel = tab["panel"] or sr.slugify(tab["title"])
                selector = f"#{tab['panel']}" if tab["panel"] else None
                page.evaluate(CLICK_TAB_JS, i)
                if selector:
                    page.wait_for_selector(selector, state="visible", timeout=15000)
                page.evaluate(UNFOLD_FIRST_JS, selector)
                page.evaluate(sr.EAGER_IMAGES_JS, selector)
                page.evaluate(sr.NEUTRALIZE_VIDEO_JS, selector)
                if page.evaluate(VIDEO_READY_JS, selector):
                    page.wait_for_timeout(SPINNER_FADE_MS)
                page.evaluate("() => window.scrollTo(0, 0)")
                sr.wait_settled(page, selector)
                name = f"{panel}.jpg"
                page.screenshot(path=str(out_dir / name), type="jpeg", quality=JPEG_QUALITY)
                size = (out_dir / name).stat().st_size
                print(f"  {name:<18} {tab['title']}  ({size // 1024} KB)", file=sys.stderr)
                shots.append({"panel": panel, "title": tab["title"], "file": name})
            context.close()
            browser.close()
    finally:
        server.shutdown()
    return shots


