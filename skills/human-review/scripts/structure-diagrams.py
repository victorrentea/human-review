#!/usr/bin/env python3
"""The Structure tab's two pictures of a Python Serverless service, read off its source.

The project the skill was born on committed its package diagram and drew its containers
from traced test runs. A Ludvig service commits neither, so this writes both — for the
merge-base and for the branch, and the diagrams step diffs the two like any committed
diagram:

**Packages** (`Packages.puml`) — the service's Python packages one level under each source
root (`src.core`, `src.handlers`, `lambdas.consumers`…), and an arrow wherever a module of
one imports from another. Each box carries its folder (`<<src/core>>`), which is what lets
the page link it and shade it by the branch's share of the lines added in it.

**Containers** (`Containers.puml`) — what the `serverless*.yml` files deploy and what drives
it: one box per stack; inside it the HTTP API (its endpoint count) and every function a
queue, topic, bus or schedule triggers; the SQS queues, SNS topics, EventBridge buses and
DynamoDB tables the stacks declare, and the ones they import by name from another stack
(`!ImportValue …-queue-arn`), outside every box; an arrow from each trigger to its
function (a schedule's carries its rate), from a queue to its dead-letter queue, and from
an EventBridge rule's bus to its target queue.

Usage:
    structure-diagrams.py --out-dir D                         # D/Packages.puml, D/Containers.puml
    structure-diagrams.py --base origin/develop --out-dir D --suffix .base
"""
from __future__ import annotations

import argparse
import ast
import importlib.util
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("endpoint_complexity", HERE / "endpoint-complexity.py")
ec = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(ec)

HEADER = ["@startuml", "' generated by human-review's structure-diagrams.py — do not edit",
          "skinparam componentStyle rectangle", "skinparam linetype ortho", ""]


def alias(*parts: str) -> str:
    return "_".join(re.sub(r"\W+", "_", p).strip("_") for p in parts if p) or "x"


# ── packages ────────────────────────────────────────────────────────────────────────────

def box_of(module: str, roots: set[str], pkgs: set[str]) -> str | None:
    """`src.core.services.x` -> `src.core`, and so does `src.core` itself; a module
    directly under a root (`src.assembly`) -> the root."""
    parts = module.split(".")
    if parts[0] not in roots:
        return None
    two = ".".join(parts[:2])
    return two if len(parts) >= 2 and two in pkgs else parts[0]


def packages(py: dict[str, str]) -> str:
    modules = {ec.module_of(p): p for p in py}
    roots = {m.split(".")[0] for m in modules if "." in m}
    # The packages one level under a root: a folder holding modules of its own.
    pkgs = {".".join(Path(p).parts[:2]) for p in py if len(Path(p).parts) > 2}
    boxes: dict[str, str] = {}
    for m, p in modules.items():
        b = box_of(m, roots, pkgs)
        if b:
            depth = b.count(".") + 1
            boxes.setdefault(b, "/".join(Path(p).parts[:depth]) if p.endswith("__init__.py")
                             or len(Path(p).parts) > depth else str(Path(p).parent))
    edges: set[tuple[str, str]] = set()
    for m, p in modules.items():
        src = box_of(m, roots, pkgs)
        if not src:
            continue
        try:
            tree = ast.parse(py[p])
        except SyntaxError:
            continue
        for node in ast.walk(tree):
            targets = []
            if isinstance(node, ast.ImportFrom):
                base = node.module or ""
                if node.level:
                    base = ".".join(m.split(".")[:-node.level] + ([base] if base else []))
                targets = [base] + [f"{base}.{a.name}" for a in node.names]
            elif isinstance(node, ast.Import):
                targets = [a.name for a in node.names]
            for t in targets:
                dst = box_of(t, roots, pkgs)
                if dst and dst != src and dst in boxes:
                    edges.add((src, dst))
                    break
    lines = list(HEADER)
    for b in sorted(boxes):
        lines.append(f'component "{b}" as {alias("p", b)} <<{boxes[b]}>>')
    lines.append("")
    lines += [f"{alias('p', a)} ..> {alias('p', b)}" for a, b in sorted(edges)]
    lines.append("@enduml")
    return "\n".join(lines) + "\n"


# ── containers ──────────────────────────────────────────────────────────────────────────

def _loader():
    import yaml

    class Loader(yaml.SafeLoader):
        pass

    def tag(loader, suffix, node):
        if isinstance(node, yaml.ScalarNode):
            value = loader.construct_scalar(node)
        elif isinstance(node, yaml.SequenceNode):
            value = loader.construct_sequence(node, deep=True)
        else:
            value = loader.construct_mapping(node, deep=True)
        return {"!" + suffix: value}
    Loader.add_multi_constructor("!", tag)
    return yaml, Loader


def ref_name(value) -> tuple[str, str] | None:
    """What a CloudFormation reference names: `("local", LogicalId)` for Ref/GetAtt, or
    `("import", name)` for an ImportValue — with `${…}` stage/service prefixes cut off."""
    if isinstance(value, dict) and len(value) == 1:
        (k, v), = value.items()
        if k in ("!Ref", "Ref"):
            return ("local", str(v))
        if k in ("!GetAtt", "Fn::GetAtt"):
            target = v[0] if isinstance(v, list) else str(v).split(".")[0]
            return ("local", str(target))
        if k in ("!ImportValue", "Fn::ImportValue"):
            name = re.sub(r"\$\{[^}]*\}-?", "", str(v)).strip("-")
            name = re.sub(r"-(arn|url|name)$", "", name)
            return ("import", name or str(v))
    if isinstance(value, str) and value.startswith("arn:"):
        return ("import", value.rsplit(":", 1)[-1])
    return None


KIND_OF = {"AWS::SQS::Queue": "queue", "AWS::SNS::Topic": "queue",
           "AWS::Events::EventBus": "queue", "AWS::DynamoDB::Table": "database",
           "AWS::S3::Bucket": "storage", "AWS::RDS::DBCluster": "database"}
LABEL_OF = {"AWS::SQS::Queue": "SQS", "AWS::SNS::Topic": "SNS", "AWS::Events::EventBus": "EventBridge bus",
            "AWS::DynamoDB::Table": "DynamoDB", "AWS::S3::Bucket": "S3", "AWS::RDS::DBCluster": "Aurora"}


def containers(sls: dict[str, str]) -> str:
    yaml, Loader = _loader()
    stacks, outside, edges = [], {}, set()
    for path in sorted(sls):
        try:
            doc = yaml.load(sls[path], Loader=Loader) or {}
        except yaml.YAMLError:
            continue
        if not isinstance(doc, dict):
            continue
        service = str(doc.get("service") or Path(path).stem)
        res = (doc.get("resources") or {}).get("Resources") if isinstance(doc.get("resources"), dict) else None
        res = res if isinstance(res, dict) else {}
        own = {}
        for lid, r in res.items():
            if isinstance(r, dict) and r.get("Type") in KIND_OF:
                own[lid] = r["Type"]
        functions = doc.get("functions") if isinstance(doc.get("functions"), dict) else {}
        http = 0
        fns = []
        for name, fn in functions.items():
            events = [e for e in (fn or {}).get("events") or [] if isinstance(e, dict)]
            kinds = [next(iter(e)) for e in events]
            if events and all(k in ("http", "httpApi") for k in kinds):
                http += 1
                continue
            fns.append(name)
            for e in events:
                (k, v), = list(e.items())[:1]
                fa = alias("f", service, name)
                if k in ("sqs", "sns", "stream"):
                    src = ref_name(v.get("arn") if isinstance(v, dict) else v) or \
                        (("import", str(v.get("topicName"))) if isinstance(v, dict) and v.get("topicName") else None)
                    if src:
                        node = _node(src, service, own, outside, "SQS" if k == "sqs" else k.upper())
                        edges.add((node, fa, ""))
                elif k == "eventBridge":
                    bus = ref_name(v.get("eventBus")) if isinstance(v, dict) else None
                    node = _node(bus, service, own, outside, "EventBridge bus") if bus else \
                        _named(outside, "default event bus", "queue", "EventBridge")
                    edges.add((node, fa, ""))
                elif k == "schedule":
                    rate = v.get("rate") if isinstance(v, dict) else v
                    rate = rate[0] if isinstance(rate, list) else rate
                    sched = _named(outside, "Scheduler", "node", "EventBridge")
                    edges.add((sched, fa, str(rate or "")))
                elif k in ("http", "httpApi"):
                    pass
        # Dead-letter queues and rules routing a bus into a queue.
        for lid, r in res.items():
            if not isinstance(r, dict):
                continue
            props = r.get("Properties") or {}
            if r.get("Type") == "AWS::SQS::Queue" and isinstance(props.get("RedrivePolicy"), dict):
                dlq = ref_name(props["RedrivePolicy"].get("deadLetterTargetArn"))
                if dlq:
                    edges.add((alias("r", service, lid), _node(dlq, service, own, outside, "SQS"), "DLQ"))
            if r.get("Type") == "AWS::Events::Rule":
                bus = ref_name(props.get("EventBusName")) if props.get("EventBusName") else None
                for t in props.get("Targets") or []:
                    target = ref_name(t.get("Arn")) if isinstance(t, dict) else None
                    if target and target[0] == "local" and target[1] in own:
                        src = _node(bus, service, own, outside, "EventBridge bus") if bus else \
                            _named(outside, "default event bus", "queue", "EventBridge")
                        edges.add((src, alias("r", service, target[1]), "rule"))
        stacks.append((service, path, http, fns, own))
    lines = list(HEADER)
    for service, path, http, fns, own in stacks:
        lines.append(f'rectangle "{service}" as {alias("s", service)} {{')
        if http:
            lines.append(f'  component "HTTP API ({http} endpoints)" as {alias("api", service)}')
        for name in sorted(fns):
            lines.append(f'  component "{name}" as {alias("f", service, name)}')
        for lid in sorted(own):
            t = own[lid]
            lines.append(f'  {KIND_OF[t]} "{lid}\\n<size:9>{LABEL_OF[t]}</size>" as {alias("r", service, lid)}')
        lines.append("}")
    for a, (label, kind, what) in sorted(outside.items()):
        lines.append(f'{kind} "{label}\\n<size:9>{what}</size>" as {a}')
    lines.append("")
    for a, b, label in sorted(edges):
        lines.append(f"{a} --> {b}" + (f" : {label}" if label else ""))
    lines.append("@enduml")
    return "\n".join(lines) + "\n"


def _named(outside: dict, label: str, kind: str, what: str) -> str:
    a = alias("x", label)
    outside.setdefault(a, (label, kind, what))
    return a


def _node(ref, service: str, own: dict, outside: dict, what: str) -> str:
    """The box a reference points at: this stack's own resource, or one outside it."""
    if ref and ref[0] == "local" and ref[1] in own:
        return alias("r", service, ref[1])
    label = ref[1] if ref else "?"
    return _named(outside, label, "queue", what if not ref or ref[0] == "local" else f"{what}, imported")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base", help="draw the merge-base with this ref, not the working tree")
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--suffix", default="", help="before .puml (`.base` for the base side)")
    args = ap.parse_args(argv)
    py, sls = ec.read_tree(args.base)
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    wrote = []
    if py:
        (out / f"Packages{args.suffix}.puml").write_text(packages(py), encoding="utf-8")
        wrote.append("Packages")
    if sls:
        (out / f"Containers{args.suffix}.puml").write_text(containers(sls), encoding="utf-8")
        wrote.append("Containers")
    print(f"[structure] {', '.join(wrote) or 'nothing'} -> {out}", file=sys.stderr)
    return 0 if wrote else 3


if __name__ == "__main__":
    raise SystemExit(main())
