#!/usr/bin/env python3
"""The database a Python service maps, as a PlantUML ER diagram — read off its models.

The Data tab draws the delta of a `DB` diagram: what the branch added to the schema in
green, what it removed struck in red. The project the skill was born on committed that
diagram, generated by a test; a Ludvig service has its schema in SQLAlchemy models and
Alembic migrations, and no diagram. So this writes one, for both sides of the diff, from
the source alone — no import, no database, no installed dependency:

  * an **entity** per declarative class with a `__tablename__` (`Column(...)` or
    `mapped_column(...)` attributes), and per `Table("name", metadata, Column(...))`;
  * a **member** per column: `name : Type`, `<<PK>>` for a primary key, `<<FK>>` for a
    foreign key, `?` for a nullable one — a column renamed by its first argument
    (`Column("orgNr", String)`) under its database name;
  * a **relationship** per foreign key, from the referencing table to the referenced one,
    `}o--||` when the column is required and `}o--o|` when it may be null.

Each entity links to the line of the class that declares it.

Usage:
    sqlalchemy-erd.py --out DB.puml                          # the working tree
    sqlalchemy-erd.py --base origin/develop --out DB.base.puml   # the merge-base
"""
from __future__ import annotations

import argparse
import ast
import subprocess
import sys
from pathlib import Path

SKIP_PARTS = {"tests", "test", "alembic", "migrations", "cdk", "node_modules", ".venv",
              "venv", "__pycache__", ".serverless", ".human-review", "initial-stack"}
COLUMN_CALLS = {"Column", "mapped_column"}


def git(*args: str) -> str:
    return subprocess.run(["git", *args], capture_output=True, text=True).stdout


def sources(base: str | None) -> dict[str, str]:
    if base:
        commit = git("merge-base", base, "HEAD").strip() or base
        names = git("ls-tree", "-r", "--name-only", commit).splitlines()
        read = lambda p: git("show", f"{commit}:{p}")
    else:
        names = git("ls-files", "--cached", "--others", "--exclude-standard").splitlines()
        read = lambda p: Path(p).read_text(encoding="utf-8", errors="replace") \
            if Path(p).is_file() else ""
    out = {}
    for p in names:
        if p.endswith(".py") and not any(part in SKIP_PARTS for part in Path(p).parts):
            text = read(p)
            # Cheap filter first: most modules map nothing.
            if "Column(" in text or "mapped_column(" in text:
                out[p] = text
    return out


def _name(node) -> str:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        return node.attr
    return ""


def _type(node) -> str:
    """`String`, `String(64)` -> `String`; `Enum(Status)` -> `Enum(Status)`."""
    if isinstance(node, ast.Call):
        head = _name(node.func)
        if head == "Enum" and node.args:
            return f"Enum({_name(node.args[0]) or '…'})"
        if head in ("ARRAY", "Array") and node.args:
            return f"ARRAY({_type(node.args[0])})"
        return head
    return _name(node)


class Column:
    def __init__(self, name, typ, pk, fk, nullable, line):
        self.name, self.type, self.pk, self.fk, self.nullable, self.line = \
            name, typ, pk, fk, nullable, line

    def member(self) -> str:
        tags = (" <<PK>>" if self.pk else "") + (" <<FK>>" if self.fk else "")
        return f"{self.name}{'?' if self.nullable and not self.pk else ''} : {self.type or '?'}{tags}"


def column(call: ast.Call, attr: str, line: int) -> Column | None:
    if _name(call.func) not in COLUMN_CALLS:
        return None
    name, typ, fk = attr, "", None
    args = list(call.args)
    if args and isinstance(args[0], ast.Constant) and isinstance(args[0].value, str):
        name = args.pop(0).value
    for a in args:
        if isinstance(a, ast.Call) and _name(a.func) == "ForeignKey" and a.args \
                and isinstance(a.args[0], ast.Constant):
            fk = str(a.args[0].value)
        elif isinstance(a, ast.Call) and _name(a.func) in ("Sequence", "Identity", "Computed"):
            continue
        elif not typ:
            typ = _type(a)
    kw = {k.arg: k.value for k in call.keywords if k.arg}
    pk = isinstance(kw.get("primary_key"), ast.Constant) and kw["primary_key"].value is True
    nullable = kw.get("nullable")
    if isinstance(nullable, ast.Constant):
        nullable = bool(nullable.value)
    else:
        nullable = not pk                   # SQLAlchemy's own default for a plain column
    if fk is None and "ForeignKey" in ast.unparse(call):
        sub = next((n for n in ast.walk(call) if isinstance(n, ast.Call)
                    and _name(n.func) == "ForeignKey" and n.args
                    and isinstance(n.args[0], ast.Constant)), None)
        fk = str(sub.args[0].value) if sub else None
    return Column(name, typ, pk, fk, nullable, line)


def tables(files: dict[str, str]) -> dict[str, dict]:
    """`{table: {"columns": [Column], "file": path, "line": n}}`."""
    out: dict[str, dict] = {}
    for path, text in sorted(files.items()):
        try:
            tree = ast.parse(text)
        except SyntaxError:
            continue
        for node in ast.walk(tree):
            if isinstance(node, ast.ClassDef):
                tname = None
                cols = []
                for stmt in node.body:
                    if isinstance(stmt, ast.Assign) and len(stmt.targets) == 1 \
                            and isinstance(stmt.targets[0], ast.Name):
                        target, value = stmt.targets[0].id, stmt.value
                    elif isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
                        target, value = stmt.target.id, stmt.value
                    else:
                        continue
                    if target == "__tablename__" and isinstance(value, ast.Constant):
                        tname = str(value.value)
                    elif isinstance(value, ast.Call):
                        c = column(value, target, stmt.lineno)
                        if c:
                            cols.append(c)
                if tname:
                    out.setdefault(tname, {"columns": cols, "file": path, "line": node.lineno})
            elif isinstance(node, ast.Call) and _name(node.func) == "Table" and node.args \
                    and isinstance(node.args[0], ast.Constant) and isinstance(node.args[0].value, str):
                cols = [c for a in node.args[1:] if isinstance(a, ast.Call)
                        for c in [column(a, "", node.lineno)] if c and c.name]
                out.setdefault(node.args[0].value, {"columns": cols, "file": path,
                                                    "line": node.lineno})
    return out


def alias(table: str) -> str:
    return "t_" + "".join(ch if ch.isalnum() else "_" for ch in table)


def puml(model: dict[str, dict]) -> str:
    lines = ["@startuml", "' generated by human-review's sqlalchemy-erd.py — do not edit",
             "hide circle", "skinparam linetype ortho", ""]
    for name in sorted(model):
        t = model[name]
        lines.append(f'entity "{name}" as {alias(name)} '
                     f'[[src://{t["file"]}:{t["line"]}{{Click to open in editor}}]] {{')
        pks = [c for c in t["columns"] if c.pk]
        rest = [c for c in t["columns"] if not c.pk]
        lines += [f"  {c.member()}" for c in pks]
        if pks and rest:
            lines.append("  --")
        lines += [f"  {c.member()}" for c in rest]
        lines.append("}")
    lines.append("")
    seen = set()
    for name in sorted(model):
        for c in model[name]["columns"]:
            if not c.fk:
                continue
            target = c.fk.split(".")[0]
            if target not in model:
                continue
            edge = (name, target, c.name)
            if edge in seen:
                continue
            seen.add(edge)
            arrow = "}o--o|" if c.nullable else "}o--||"
            lines.append(f"{alias(name)} {arrow} {alias(target)} : {c.name}")
    lines.append("@enduml")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base", help="the schema at the merge-base with this ref")
    ap.add_argument("--out", help="where to write the .puml (default: stdout)")
    args = ap.parse_args(argv)
    model = tables(sources(args.base))
    text = puml(model)
    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(text, encoding="utf-8")
        print(f"[erd] {len(model)} tables -> {args.out}", file=sys.stderr)
    else:
        sys.stdout.write(text)
    return 0 if model else 3


if __name__ == "__main__":
    raise SystemExit(main())
